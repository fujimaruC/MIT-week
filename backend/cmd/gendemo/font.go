// textWidth is the pixel width of s at the given scale (1px spacing).
func textWidth(s string, scale int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return n*6*scale - scale
}

// drawText renders s in upper case with its top-left corner at (x, y).
func drawText(img *image.RGBA, s string, x, y, scale int, c color.RGBA) {
	cx := x
	for _, r := range strings.ToUpper(s) {
		g, ok := glyphs[r]
		if !ok {
			g = glyphs['?']
		}
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if g[row][col] != '#' {
					continue
				}
				fill(img, image.Rect(cx+col*scale, y+row*scale, cx+(col+1)*scale, y+(row+1)*scale), c)
			}
		}
		cx += 6 * scale
	}
}

func fill(img *image.RGBA, r image.Rectangle, c color.RGBA) {
	r = r.Intersect(img.Bounds())
	for y := r.Min.Y; y < r.Max.Y; y++ {
		for x := r.Min.X; x < r.Max.X; x++ {
			img.SetRGBA(x, y, c)
		}
	}
}
